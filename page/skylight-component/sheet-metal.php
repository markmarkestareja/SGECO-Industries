<h2 class="p-large reveal2">Sheet Metal Fabrication for Tubular Skylights</h2>

<div class="skylight-component-p reveal2 reveal2-fade">
    <p>One of the main functions carried out in the SG Eco factory is sheet metal fabrication. Whether it be as simple
        as cutting down sheets, or something more complex, SG Eco can handle it. With a number of guillotines, press
        brakes, inclinable presses, rollers, spot welders, elbow machine, hydraulic presses and a CNC router, we have
        the machinery to make just about anything out of sheet metal.</p>

    <p>SG Eco Industries stock the following sheet metal for production:</p>
    <ul>
        <li>0.45mm Stainless Steel – 430 Grade – Bright Annealed</li>
        <li>0.55mm Zincalume</li>
        <li>0.75mm Zincalume</li>
        <li>0.40mm Colorbond “Surfmist”</li>
        <li>0.55mm Colorbond “Nightsky”</li>
        <li>0.50mm Alanod Miro Silver Aluminium</li>
        <li>1.00mm Aluminium – Grade 5005 H34</li>
        <li>0.70mm Aluminium – Grade 5005 H34</li>
        <li>1.00mm Aluminium – Grade 1200 H0</li>
        <li>0.70mm Aluminium – Grade 1200 H0</li>
    </ul>

</div>


