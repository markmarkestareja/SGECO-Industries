<h2 class="p-large reveal2">Corrugated Roof Flashing</h2>
<div class="skylight-component-p reveal2 reveal2-fade">
    <p>Manufactured by SG Eco Industries Inc., Corrugated Flashing eliminates the need for using lead on tile roof
        flashings. Comprising of 2 layers of aluminium with rubber inserted between, the corrugated flashing is flexible
        enough to mould around the tiles, and heavy enough to stay in position once installed. Produced in a mill or
        powdercoated finish, and in any length up to 1600mm long this corrugated flashing can be incorporated into
        almost any product.</p>
    <p>We can source other materials for custom fabrication purposes if required.</p>
</div>