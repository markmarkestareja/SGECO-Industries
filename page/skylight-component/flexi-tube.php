<div class="skylight-component-p reveal2 reveal2-fade">
    <p>We currently offer 41 different diameters ranging from 150mm to 1267mm. Many of the larger sizes are used for
        creating square or rectangular tubing. Our round Flexi-tube™ is supplied in 1.5m to 10m lengths, where as the
        square and rectangular are supplied in lengths up to a maximum of 3m.</p>

    <p>Sizing of the square and rectangular range from 350mm × 350mm up to 995mm × 995mm. If we don’t have the size you
        are looking for, custom sizing is available, depending on the size and quantity required. The square and
        rectangular Flexi-tube™ can have an additional layer of tape added to the corners to add durability and
        strength.</p>
</div>

