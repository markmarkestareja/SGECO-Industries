<h2 class="p-large reveal2">Flexible Reflective Tubing for Skylights</h2>

<div class="skylight-component-p reveal2 reveal2-fade">
    <p>Flexi-tube is the standard tubing used in all of our Sky Tunnel Skylights, Sola Skylights, Lightwell Skylights &
        Direct Skylights kits. It suits most applications up to 3m in length. Our Flexi-tube comprises two layers of
        metalized polyester.</p>

    <p>Installation of Flexi-tube is very easy, and the performance is outstanding. Flexibility allows the installation
        of the Roof Parts and Ceiling Parts to be off centre, so avoiding any obstructions in the attic space is simple.
        Providing up to 86% reflectivity, SG Eco’s Flexi-tube™ is a cost effective and reliable component in any
        skylight kit.</p>
</div>


<div class="diffuser-img reveal2">
    <img src="asset/img/skylight-component/Square Flexi-tube.webp" alt="Square Flexi-tube">
