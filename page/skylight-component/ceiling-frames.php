<h2 class="p-large">Ceiling Frames</h2>
<div class="skylight-component-p">
    <p>SG Eco Industries, Inc. manufactures Ceiling Frames, also known as “Ceiling Trims” or “Ceiling Surrounds” for a
        wide variety of applications, but predominantly used in Skylights. The ‘T’ bar used for the frame is an extruded
        Aluminum section, which is then Powder Coated in a Pearl White Finish. Each frame uses 8 x brackets (2 per
        corner). Frames can be made any size.</p>

