<h3>Vari-lights Light Adjustor for Sky Tunnel Skylights</h3>
<div class="skylight-component-p">
    <p>The Vari-light allows you to control the amount of daylight entering the room, all by remote control. The
        Vari-light runs on 12V DC Electricity, and with a 2W motor usesalmost no power to operate.</p>
    <p>The remote control has 3 buttons – Open, Close & Stop. Press the open or close button once to start the
        Vari-light, and when you get to the desired level of daylight – press Stop. When the unit is closed the unit
        will still allow a minimal amount of light to enter the room.</p>
    <p>The Vari-light can be controlled by the (MARCS) remote system.</p>
    <p>Manufactured and distributed by SG Eco Industries, Inc.</p>

