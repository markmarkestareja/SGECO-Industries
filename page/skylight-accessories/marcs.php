<h3>Multiple Accessory Remote Control System (MARCS)</h3>
<div class="skylight-component-p">
    <p>One Remote Control to operate the following accessories:</p>
    <ul>
        <li>Vari-light</li>
        <li>Power Kit – Exhaust Fan</li>
        <li>Electric LED Light</li>
    </ul>
    <p>The system uses a “Learning” type remote allowing single or multiple units to be controlled by the one handheld
        remote control – the choice is yours.</p>
    <p>The Receiver Input is 12V with a maximum load of 70W. The Exhaust Fan draws 18W, the Vari-light draws 2W and LED
        Lighting System approx 30W. Transformer Input 110V-240V, 50/60hz.</p>

</div>