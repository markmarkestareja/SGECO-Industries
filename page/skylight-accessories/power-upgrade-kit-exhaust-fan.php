<h3>Skylight Powered Exhaust & Ventilation Fan</h3>
<div class="skylight-component-p">
    <p>The Power Kit – Exhaust Fan for the Sky Tunnel XL2 is a ventilation system ideal for small bathrooms, toilets or
        anywhere you need to exhaust air from a room which also requires daylighting. The fan motor runs on 12V DC
        electricity, and with a 18W motor uses approx Php0.22 (less than USD0.01) per hour.</p>
    <p>The Exhaust Fan is located in the stainless steel take off unit just above the ceiling. The exhausted air is
        pushed up through a 150mm diameter flexible tube and out through a cowl on the roof parts of the Sky Tunnel™.
        The design of this system means you only have one roof penetration and one ceiling fixture that provide your
        ventilation & daylighting solution.</p>
    <p>The Power Kit can be controlled by the MARCS remote system.</p>
    <p>Manufactured and distributed by SG Eco Industries, Inc.</p>

