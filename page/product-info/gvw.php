<div class="how-gvw-work">
    <div class="how-gvw-work-text">
        <h2>How It Works</h2>
        <ol>
            <li>Wind energy creates a positive flow through the Green-vent Wind and the head of the Ventilator to
                rotate.</li>
            <li>As the Green-vent Wind rotates, an area of low pressure is created on the leeward side of the
                ventilator. The air that is drawn out between the vertical vanes of the ventilator head feeds this low
                pressure zone.</li>
            <li>This process allows a continuous air flow through the Green-vent Wind which, provided adequate inlet
                vents are installed, will replace the hot stale air inside the building with cooler and fresh air from
                outside the building.</li>
            <li>The rotation of the Green-vent Wind also creates centripetal forces which will expel the air outwards
                from the edge of the vanes. Temperature differentials and thermal currents will also allow the
                ventilation process to occur, even with no wind.</li>
        </ol>
