        <h1>Environment Control System (Optional)</h1>

        <div class="attic-img img-mobile">
            <img src="asset/img/gvs/green-vent-ecs.webp" alt="">
        </div>

        <p>The ECS is an automated system for running the fan when the environmental conditions demand it. If the
            temperature or humidity in the attic space is too high the fan will operate. Once conditions return to lower
            levels, the fan will stop running. When running on mains power the fan will run for 8 minutes every half
            hour.</p>

        <div class="gvs-inner-text">
            <p style="font-size: 25px;">The settings of the ECS as as follows:</p>
            <p>Temperature Control: Turns fan ON at 27°C & OFF at 25°C.</p>
            <p>Humidity Control: Turns fan ON at 75%RH & OFF at 65%RH.</p>
