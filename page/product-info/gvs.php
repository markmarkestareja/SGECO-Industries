        <h1>Green-Vent Solar Ventilator</h1>

        <div class="attic-img img-mobile">
            <img src="asset/img/gvw/GVS - Panel Swivel.webp" alt="">
        </div>

        <p>The Green-Vent Solar Attic Extraction Fan is an attic ventilation system that can be installed into
            commercial or residential rooves to remove the trapped heat between the ceiling and the roof. The
            temperature inside your roof/attic space can reach temperatures up to 70°C (170°F) during the summer months
            which creates a heat load on ceiling insulation and air conditioning duct work. Green-Vent Solar utilizes
            the renewable energy source, the sun, meaning it costs you nothing to quietly exhaust the hot air and help
            reduce the cooling costs of your building.</p>

        <p>During the winter months any moisture laden air trapped inside your roof/attic space can condense in the
            cooler temperatures, resulting in the growth of mold and mildew. Circulating clean fresh air will reduce the
            occurrence of this and prolong the life of your roof.</p>

