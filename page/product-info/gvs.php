    </div>

    <div class="how-gvw-work-card-container">
        <div class="how-gvw-work-card">
            <h3>During Summer</h3>
            <div class="how-gvw-work-card-img">
                <img src="asset/img/gvs/GVS - Summer.webp" alt="">
            </div>
            <ol>
                <li>Heat transfers through your roof and into your attic space, increasing the temperature.</li>
                <li>The Green-vent Solar Attic Extraction Fans photovoltaic solar panel converts sunlight energy into
                    electrical energy.</li>
                <li>The electrical energy drives a motor that spins a fan blade, which in turns exhausts the heat from
                    your attic.</li>
            </ol>
        </div>

        <div class="how-gvw-work-card">
            <h3>During Winter</h3>
            <div class="how-gvw-work-card-img">
                <img src="asset/img/gvs/GVS - Winter.webp" alt="">
            </div>
            <ol>
                <li>Heat trapped inside your attic space can melt the snow accumulated on the roof of your home. As the
                    water drips down, it refreezes at the cooler eaves, leading to ice-dams forming along the lower edge
                    of the roof. These dams allow water penetration into the roof causing severe damage.</li>
                <li>Even during winter months, the Green-vent Solar Attic Extraction Fans photovoltaic solar panel can
                    convert sunlight energy into electrical energy.</li>
                <li>The electrical energy drives a motor that spins a fan blade, which in turns exhausts the moisture
                    laden air from your attic and preventing mold & mildew build up, as well helping prevent any ice
                    damming.</li>
            </ol>
        </div>
