        <h1>How Sky Tunnel Skylight Works</h1>
        <p class="p-large">How We Capture Daylight For You</p>
        <ol>
            <li>Sunlight enters the Sky Tunnel Dome. The UV stabilized, high impact, acrylic dome has a very high light
                transmittance allowing more of light to enter into the tube.</li>
            <li>Sunlight is reflected through the Sky Tunnel mirror-like tube. The sunlight then reflects down a highly
                reflective mirror like tube, connecting the roof to the ceiling. The high reflection of the tube means
                the performance is still very efficient, even during times when available sunlight is reduced such as
                early morning, late afternoon and during overcast conditions.</li>
            <li>Sky Tunnel Diffuser then evenly disperses the sunlight into the building. The sunlight that has
                reflected down the tube then passes through two layers of textured acrylic, which have been specifically
                designed to spread the light evenly around the room. These diffusers also have a very high light
                transmittance allowing more of light to pass through them.</li>
        </ol>
