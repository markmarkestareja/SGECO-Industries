        <div class="news-update-detail">
            <p>SG Eco Industries Inc. joined the “Recyclables Collection Event 2013” as part of Philippine Environment Month celebration on June 14, 2013. In preparation for this event, SG Eco collected empty ink cartridges, broken appliances and used batteries. The Clark Development Corporation (CDC) through its Environmental Management Department (EMD) together with the Environmental Practitioners Association (EPA) in coordination with the DENR Environmental Management Bureau Region III, held the event for Clark locators and residences at CDC-EMD Office, E. Aguinaldo corner CP Garcia Streets, Clark Freeport Zone. Recyclers and scrap buyers are Ink Line Trading for cartridges, Oriental and Motolite Corp. for used batteries, Semi-recycling Co. Inc for metal, electronic and plastic scrap and Dolomatrix Phils. for treatment of busted light.</p>
