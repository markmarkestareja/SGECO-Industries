            <p>Skylights are considered to be one of the most reliable energy-saving devices utilizing the renewable
                energy of the sun in order to provide natural lighting inside an office or home.</p>
            <p>With proper installation and positioning, this lighting device can allow up to five times more light than
                a regular window thereby improving the occupants’ utility of the interior space in a comfort in a highly
                cost-effective way.</p>
            <p>Skylights can also enhance the curb value and aesthetic appeal of your property as well as contribute to
                reducing the Carbon Footprint that produces.</p>
            <p>So if you want to enjoy the benefits it offers, here are some fundamental questions that you need to
                consider before installing skylights.</p>
            <h2>Are Skylights Applicable to any Size of House?</h2>
            <p>Skylights can be installed in any room of a house (single or multi-storey) as long as there is suitable
                access and sufficient ventilation as condensation can occur as it conveys light energy into the
                building.</p>
            <h2>What is Your Roof Framing at Home?</h2>
            <p>Before installing skylights, you should determine the kind of roof frame you have in your house.
                Basically, skylights can be installed on these two commonly used roof framing system- conventional and
                truss roof frame.</p>
            <p>Larger size skylights can be installed on a conventional roof frame while truss roof frames usually
                require smaller skylights which can accommodate a maximum truss center of 2 feet.</p>
            <h2>Where is the Best Place for Your Skylights?</h2>
            <p>The best place to position your skylights should always be clear of any obstructions such as electrical
                wires, water heater pipes, heat and A/C ducts or anything that might serve as structural obstacle.</p>
            <p>If you have a limited roof space, you can re-route the pipes or cable wires to clear out the space that
                you need in order to install them.</p>
            <h2>Does the interior colour scheme of your space affect the performance of Skylights?</h2>
            <p>Yes it does. Lighter, brighter colors will tend to reflect daylight around the room while dark colors
                will tend to absorb it. The best solution for this is to adjust the size or quantity of skylights to
                provide sufficient lighting inside your house.</p>
