        <div class="news-update-detail">
            <p>Energy demand in Asia is rising – how to get yours for free. Visit us today at eco.ph!</p>
            <p><a href="http://www.eco-business.com/news/why-smart-money-looking-clean-energy-asia/">(Article First
                    Published on: eco-business.com | February 12, 2015)</a></p>
            <p>Driven by rising urbanisation and a growing middle class, demand for energy in Southeast Asia is set to
                increase by a staggering 80 per cent between 2013 and 2035 - a rise equivalent to the current demand in
                Japan, estimates the International Energy Agency.</p>
            <p>This supports a near tripling of the region’s economy, but one of the biggest challenges facing the
                region is balancing the need for affordable energy with curbing greenhouse gas emissions, the main cause
                of climate change.</p>
            <p>Clean, renewable sources will have to become a vital part of the energy mix, even as reliance on oil
                imports rises across the region. Bloomberg New Energy Finance expects that US$2.5 trillion will be spent
                on renewable technologies in Asia Pacific by 2030 – a hole that governments alone cannot fill.</p>
            <p>Experts say the private sector holds the key to this funding shortfall. The good news is, there already
                is growing interest from the private sector to invest in the region’s clean energy sector.</p>
            <p>These include private equity funds, companies and increasingly, family offices, which are gradually
                taking to the concept of sustainable investing.</p>
            <p>Sustainable investing refers to an investment approach that seeks financial return while emphasizing
                social good. This usually involves promoting environmental stewardship, consumer protection, human
                rights, and diversity, to name a few.</p>
            <p>“Clean energy is definitely a large trend in sustainable investing and we really see that happening
                across the region,” says Jessica Robinson, chief executive of the Association for Sustainable &
                Responsible Investment in Asia (ASrIA).</p>
            <p>In a report called “Asia Sustainable Investment Review”, published last December, ASrIA studied
                sustainable investment strategies and practices by investors in Asia.</p>
            <p>“We are seeing a lot of positive trends, and one is that governments are trying to bringing in private
                capital to co-share not only the capital but the returns and risks,” Robinson adds.</p>
            <p>Potential investors are now more comfortable with the risks involved in the building and running of power
                assets because returns have been attractive and policy support is gradually increasing albeit the level
                of support varies across the region.</p>
            <p>Furthermore, an ecoystem of companies that provide services and hardware in clean energy is emerging. All
                these factors are contributing to the growing awareness among private investors that the clean energy
                industry is viable.</p>
            <p>Nonetheless, they still need to be nudged to invest, mainly by governments, and a good way to do that is
                to co-share risks.</p>
            <p>“Companies hate uncertainty… (so) this is where policy support comes in,” Robinson says.</p>
            <p>For example, governments can back a fund specialising in clean and renewable energy and match the
                private-sector contributions, which Indonesia has done. They can also help with valuing projects more
                effectively by putting a price on carbon, she adds.</p>
            <p>“More bankers than engineers”</p>
            <p>In the meantime, the potential for the private sector is in Southeast Asia is huge.</p>
            <p>“There is more money wanting to go into projects than there are projects,” says Michael Quah, professor
                of chemical and biomolecular engineering at the National University of Singapore (NUS).</p>
            <p>“When you go to any conference on financing, 90 percent of them are bankers and money types. The rest are
                engineers,” says the professor, who is also the director of the NUS Energy Office.</p>
            <p>Berkeley Energy, Armstrong Asset Management and Equis Funds Group are among the private groups that
                started investing in renewable energy projects in the region in the past decade.</p>
            <p>U.K.’s Berkeley Energy’s Renewable Energy Asia Fund has stakes in small hydro, wind, geothermal, solar,
                landfill gas and biomass projects in Asian developing markets, focusing on the Philippines and India.
            </p>
            <p>Armstrong’s Southeast Asia Clean Energy Fund, a private-equity fund based in Singapore, manages US$164
                million of investments in utility-scale renewable energy and resource efficiency projects in Southeast
                Asia.</p>
            <p>Armstrong’s chief executive officer Andrew Affleck said the fund’s early participation in the sector has
                generated goodwill among governments in the region.</p>
            <p>“There are compelling reasons for private finance to invest in the renewable energy sector – and the
                subsequent success of companies like us should eventually encourage broader participation from large
                private sector institutions,” Armstrong told Eco-Business.</p>
            <p>“New initiatives are being put in place to increase such participation,” he adds. For example,
                governments are reaching out to private companies to collaborate on public-private partnerships and
                working on increasing tax incentives for green projects. “</p>
            <p>Singapore-based Equis Funds Group, meanwhile, invests in Soleq, a solar utility also based in the city
                that owns and operates 70 percent of 10 solar facilities - totalling 91MW - in Thailand.</p>
            <p>Soleq is also financing the construction of two projects in Philippines totalling 50MW, with the rights
                to acquire and fund an additional 150MW of solar projects.</p>
            <p>There are compelling reasons for private finance to invest in the renewable energy sector – and
                subsequent investment success of people like us should eventually encourage broader participation from
                large private sector institutions.</p>
            <p>Andrew Affleck, chief executive officer, Armstrong Asset Management.</p>
            <p>A lot of work is also being done by development finance institutions such as International Finance
                Corporation (IFC), The Netherlands Development Finance Company (FMO), Germany Investment and Development
                Corporation (DEG), Proparco, The Global Energy Efficiency and Renewable Energy Fund (GEEREF), Asian
                Development Bank (ADB) and Obviam in the region.</p>
            <p>They invest in private funds such as Armstrong’s as well as directly in projects, providing both debt and
                equity.</p>
            <p>The name is Bond, Green Bond</p>
            <p>While the efforts by the private sector to invest in clean energy projects have been promising, far more
                is needed in terms of fund-raising for projects in the region.</p>
            <p>One innovative funding stream that could potentially make a huge difference is green bonds.</p>
            <p>Companies that want to build, for instance, wind or solar farms, issue these bonds, which promise a
                certain return over the life of the project. Investors fund them by buying the bonds.</p>
            <p>Currently, many investors are institutions such as private companies, commercial banks, insurance firms,
                central banks and other government bodies, asset managers, and pension funds.</p>
            <p>For these private-sector investors, such credit-worthy fixed income opportunities may be attractive as
                they provide steady returns over five to 20 years.</p>
            <p>In recent years, green bonds have raised money for clean energy, mass transit, and other low-carbon
                projects that help countries adapt to and mitigate climate change.</p>
            <p>Since the first green bond was developed by the World Bank and Skandinaviska Enskilda Banken (SEB) in
                2007, the global market for such bonds has grown rapidly at a compound annual rate of more than 50
                percent, according to S&P Dow Jones Indices, which runs the S&P Green Bond Index consisting of 150 such
                issuances.</p>
            <p>In Asia, the market is tiny but growing, says Julia Kochetygova, senior director of global equities and
                strategy, S&P Dow Jones Indices, in a January 2015 report “Climate Change, Green Bonds and Index
                Investing: The New Frontier”.</p>
            <p>“If the current trends continue, (the global green bond market) could grow from USD$150 billion to
                USD$200 billion over the next three to five years, thus providing an array of investment opportunities
                to long-term fixed income investors,” she writes in the report.</p>
            <p>Last July, Taiwan’s Advanced Semiconductor Engineering became the first Asian company to sell green
                bonds, issuing US$300 million of three-year bonds.</p>
            <p>They received more than US$2 billion in orders, reflecting the huge demand for such products and paving
                the way for more companies in the region follow in its footsteps.</p>
            <p>Institutions that are advocating green bonds include ADB’s Credit Guarantee and Investment Facility
                (CGIF), which provides credit guarantees to companies that want to issue local-currency bonds in
                Southeast Asia.</p>
            <p>The CGIF is focusing on green bonds this year and hopes to lead the way in the development of green bond
                in the region, CGIF’s chief executive Kiyoshi Nishimura told Global Capital.</p>
            <p>The agency knows there are huge green investment needs in Asean countries, especially in renewable energy
                and energy-efficiency areas, and there is almost no precedent for green bonds in Asia, Global Capital
                reported. That is why it is focusing on green bonds.</p>
            <p>“Most likely, our initial projects for green bonds will be for renewable energy or energy efficient
                investments,” Nishimura says. “We are already working on transactions involving renewable energy
                investments in the Philippines (geothermal) and Laos (hydro) and exploring if they can be structured as
                green bonds.”</p>
            <h2>Overcoming Challenges</h2>
            <p>Despite the rosy outlook for green energy projects in Southeast Asia, challenges do exist, and can be as
                simple as the lack of communication between the public and private sectors.</p>
            <p>“I think an issue is there’s not enough engagement between the private sector and government. So there’s
                a big question on where the opportunities are and where the private sector can help,” says ASrIA’s
                Robinson.</p>
            <p>Affleck agrees, but adds that it’s “getting better in some countries.”</p>
            <p>The Philippines Energy Regulatory Commission, for example, now holds timely public stakeholder
                consultations to address problems, he says. “And they do try to solve them.”</p>
