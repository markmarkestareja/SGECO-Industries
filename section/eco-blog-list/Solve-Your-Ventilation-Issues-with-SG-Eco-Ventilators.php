            <h2>Residential Ventilators</h2>
            <h3>Under Eave Vents</h3>
            <p>Under eave vents are used as inlet vents for residential ventilators. These inlet vents replace the hot and stale air inside the house with its specially designed large openings between the vanes for a constant airflow through your attic or roof space.</p>
            <h4>Why Do You Need Them?</h4>
            <p>Under Eave vents improve the efficiency of any roof ventilation system but also prevent insects from entering your attic or roof space with its built-in insect mesh. Buying this product will not only let you keep your house safe from extreme weather conditions but also protects your family from disease-carrying insects.</p>
            <h3>Whirlwind Roof Ventilator</h3>
            <p>This ventilator works in two ways. It exhausts hot stale air during summer and moisture-laden air during winter. The lightweight marine grade aluminum structure and low torque double bearing system allow the Whirlwind to operate more efficiently, even at low wind speeds.</p>
            <h4>Why Do You Need Them?</h4>
            <p>If you are living in a low-wind area, this product is right for you.  Its low torque bearings and large vane openings provide a better air flow even at lower wind speed.</p>

            <h2>Solar Powered Ventilators</h2>
            <h3>Solar Attic Extraction Fan</h3>
            <p>The Green-Vent Solar Attic Extraction Fan is an attic ventilation system that can be installed into commercial or residential roofs to remove the trapped heat between the ceiling and the roof. It uses photovoltaic solar panels that automatically convert the natural solar energy from the sun into usable electrical energy.</p>
            <h4>Why Do You Need Them?</h4>
            <p>Solar Attic Extraction Fan prolongs the life of your roofing system as it quietly vents the hot air between your building’s ceiling and roof utilizing its modern design and solar panels.</p>

