        <h1 class="p-large">Families Warm to Solar Power: Rising energy bills mean 60% of households are now considering installing panels</h1>
    </div>
    <div class="news-update-img-text">
        <div class="news-update-img"><img src="asset/img/resources-menu/eco-blog/roofsolar.webp" alt="roofsolar"></div>
        <div class="news-update-detail">
            <p><a
                    href="http://www.dailymail.co.uk/news/article-3049593/Families-warm-solar-power-Rising-energy-bills-mean-60-households-considering-installing-panels.html">(Article
                    First Published on: dailymail.co.uk | April 21, 2015)</a></p>
            <ul>
                <li>Demand is being fuelled by solar panels provided through 'rent-a-roof'</li>
                <li>Companies offer free installation in return for pocketing surplus energy pay</li>
                <li>Market researchers say demand for solar panels has exploded since 2010</li>
            </ul>
            <p>Rising energy bills are driving more homeowners into installing solar panels on their roofs. And experts
                say there is still ‘strong growth potential’, with three fifths of householders said to be considering
                the option. Demand is being fuelled by solar panels provided through ‘rent-a-roof’ schemes, whereby
                companies install the system free in return for pocketing payments for the surplus energy that is fed
                into the National Grid.</p>
            <p>Soar in demand: Rising energy bills are driving more homeowners into installing solar panels on their
                roofs. Demand is being fuelled by 'rent-a-roof' schemes and the Government's Green Deal finance
                initiative.</p>
            <p>However, a quarter of respondents to a survey by market researchers Mintel would either buy the panels
                themselves to get the feed-in tariff or use the Government’s Green Deal finance scheme.</p>
            <p>Claudia Preedy, a Mintel analyst, said: ‘Although the market remains in its infancy, demand for solar
                panels has exploded since 2010 and there continues to be strong growth potential.</p>
            <p>'The market was originally driven by residential roof-top installations, reflecting the introduction of
                the FIT scheme in April 2010.</p>
            <p>'However, in 2013 and particularly during 2014, there was a shift in focus from roof-top to large-scale
                ground mounted installations.</p>
            <p>'These policy changes reflect the current government's desire to see a shift in solar developments from
                large scale ground-mounted towards mid-scale building-mounted, commercial and industrial onsite
                generation and domestic deployment.'</p>
            <p>Of the homeowners who have solar panels on their roofs, seven out of ten paid for them themselves and
                only a fifth used the 'rent-a-roof' scheme.</p>
            <div class="news-update-img"><img src="asset/img/resources-menu/eco-blog/solar power 2.webp"
                    alt="solar power 2"></div>
            <p>Reaping the benefits: A survey by market researchers Mintel found that of the homeowners who have solar
                panels on their roofs, seven out of ten paid for them themselves and only a fifth used the rent-a-roof
                scheme.</p>
            <div class="news-update-img"><img src="asset/img/resources-menu/eco-blog/solarpanel2.webp"
                    alt="solarpanel2"></div>
            <p>Not everyone is convinced: Two fifths of those surveyed want nothing to do with the technology, Mintel
                found, with three out of ten concerned about maintenance costs or believing their roof was not suited.
            </p>
            <p>But two fifths want nothing to do with the new technology, with three out of ten believing their roof was
                not suited or were concerned about replacement or maintenance costs, while a quarter planned to move out
                before they get the financial investment back.</p>
            <p>Only a sixth were concerned about how solar panels affecting housing prices while less than a tenth said
                they spent not enough time in their home during the day to benefit from the daytime electricity
                generated by these solar panels.</p>
            <p>Ms Preedy added: 'Despite frequent changes in government policy and other factors, such as the strong
                drop in installation costs in recent years, the solar industry has proved resilient and has shown that
                it can reinvent itself within a changing landscape.</p>
            <p>'The industry is expected to continue to do so in the foreseeable future, even with the uncertainties
                regarding future government policies.'</p>
