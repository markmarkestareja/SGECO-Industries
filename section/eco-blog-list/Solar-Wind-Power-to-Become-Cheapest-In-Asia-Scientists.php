            <p>Finnish scientists believe that renewable energy sources, such as solar and wind power, will become the
                cheapest energy for consumers in Asia in next 10 years.</p>
            <p>A joint project conducted by Finnish Technical Research Center (VTT) at the Lappeenranta University of
                Technology and the University of Turku has successfully modelled comprehensive energy systems based
                entirely on renewable energy sources for China, South Korea and Japan, Xinhua reported.</p>
            <p>The project has recently won an award in Japan for its pioneering simulation work.</p>
            <p>China, a leading energy consumer in the world, has become the world's largest investor in solar and wind
                energy, said VTT's Pasi Vainikka.</p>
            <p>"China possesses significant wind and solar energy resources, so a power network based on renewable
                energy sources has the potential to become profitable very quickly," Vainikka was quoted as saying.</p>
            <p>The researchers who participated in the project predicted that the price of solar electricity will drop
                by half within 10 to 15 years, so that the relative industries will become more profitable.</p>
