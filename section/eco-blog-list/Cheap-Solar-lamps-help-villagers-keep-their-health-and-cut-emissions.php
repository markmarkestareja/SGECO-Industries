            <p>In Kenya, where less than a quarter of the 45-million population has access to electricity, a solar lamp
                project is helping rural communities save money on expensive and harmful fuel while reducing carbon
                emissions. The Use Solar, Save Lives initiative was set up in 2004 by Evans Wadongo, 29, an engineer who
                experienced the dangerous effects of kerosene lamps growing up in a western Kenyan village. Studying
                close to an open flame, he was exposed to kerosene smoke, notorious for provoking breathing and vision
                defects, which left him with permanent eye problems.</p>
            <p>Determined to make a difference, Wadongo designed an alternative – a simple, sun-powered lantern dubbed a
                MwangaBora, which means “good light” in Swahili. The lamp is cleaner and greener, and also cuts costs.
                “For a family that earns two dollars a day, kerosene takes about 30-40% of their daily income. If
                they’re able to save that, it really makes a big difference,” says Wadongo. The lamps are made from
                locally sourced scrap metal and fragments of solar panels that charge a battery-powered LED light, while
                a USB port can be built into the base, offering an easy way to charge phones and radios.</p>
            <p>Instead of importing solar technology from a mass producing country such as China, groups of young people
                are trained to manufacture the lamps. These are then given to women’s groups, who use the money they
                save to set up small businesses such as poultry farming or beekeeping. “When women have their own
                income, they spend it on their families and the whole community benefits,” says Wadongo. Winning an
                international Seed award in 2011 helped the organisation to circulate lamps around the country – there
                are now more than 50,000 MwangaBora used in Kenya alone. Fundraising exhibitions featuring the lamps
                have taken place in New York and at thePavilion of Art and Design in London, and Wadongo was named as
                one of CNN’s top 10 heroes in 2010. At the 2012 London Olympics, he was selected as one of four
                torchbearers for Kenya.</p>
            <p>Despite these accolades, and donations from around the world, Wadongo says that financing the project is
                a challenge due to its long-term nature. Each lamp costs $25, which covers materials, training and
                distribution. The women’s groups can use money from their successful businesses to buy more lamps,
                creating a micro-finance system. “We want to make sure that in every community we get into, we leave
                them not only with lamps but with increased income levels,” he says.</p>
            <p>The project has already taken off in Uganda and Wadongo is looking to further expansion. “We still have a
                whole lot of work to do in Kenya. By 2018, we want to be working in at least five countries in
                sub-Saharan Africa and have a million people benefiting from our program. Eventually we want to be able
                to do the same in South America, for example.”</p>
            <p>And the impact could be global. Solar power saves lives by reducing the risk of fire caused by open
                flames and by improving villagers’ economic and educational prospects, but also by helping to save the
                planet, says Wadongo. “Burning one litre of kerosene produces 2.6kg of CO2, so with more than a billion
                people worldwide using it every day, you can imagine how much is emitted into the environment.”</p>
