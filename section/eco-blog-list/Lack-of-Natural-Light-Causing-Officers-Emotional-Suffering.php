        <h1 class="p-large">Lack of Natural Light Causing Officers 'Emotional Suffering'</h1>
    </div>
    <div class="news-update-img-text">
        <div class="news-update-img"><img src="asset/img/resources-menu/eco-blog/prison.webp" alt="prison"></div>
        <div class="news-update-detail">
            <p>An absence of natural light in some police custody suites causes personnel and detainees "emotional
                suffering" as well as headaches and eye strain, it has been claimed.</p>
            <p>The fact that many custody suites are devoid of windows has been linked to burnout and psychological
                anxiety among staff, and this is exacerbated by harsh strip lighting, said Andy Ward from the UK’s
                Police Federation.</p>
            <p>Mr. Ward, the Federation's joint lead on custody, cited research by occupational health expert Dr.
                Jonathan Houdmont which showed a link between a lack of access to natural light and exhaustion.</p>
            <p>"I did six years solid in custody suites where there was absolutely no natural light," Mr. Ward said
                following a conference in London at which he raised the issue. "You don't necessarily think about it at
                the time, but when there are dark mornings and dark nights, sometimes you don't know whether it is day
                or night."</p>
            <p>Attempts to "design in" natural light in custody environments have been stymied by the imperative to
                maintain security and privacy.</p>
            <p>Installing windows could mean detainees being able to see co-defendants being brought into custody -
                which could wreck cases - and possibly increase the chance of people escaping from their cells.</p>
            <p>Some custody suites are located in basements underneath police stations in order to keep detainees
                isolated.</p>
            <p>Dr. Houdmont told PoliceOracle.com his research had found "a positive correlation between reports of a
                problematic lack of natural light and burnout or emotional exhaustion."</p>
            <p>He added: "The less natural light people have at work, the more knackered they are, to put it bluntly."
            </p>
            <p>There was evidence this also impacted on custody staff members' commitment and intention to remain in
                post, he said.</p>
            <p>Depression and anxiety have also been linked to a lack of natural light - as have headaches and strained
                eyes.</p>
            <p>Dr. Houdmont suggested using translucent glass or Perspex, rather than transparent glass so that
                detainees could not see co-defendants being brought in.</p>
            <p>In some newbuild custody suites glass roofs have been installed to try and address the problem.</p>
            <p>Marcus de Guingand, Managing Director of occupational health company Third Pillar of Health, said: "In
                offices and homes most lights are what we would term yellow lights, whereas light from the sun, which
                gives us melatonin [the 'circadian rhythm hormone'] is more on the blue or green part of the spectrum."
            </p>
            <p>This study suggests that natural light is not only desirable in homes and workplaces but even in police
                custody suites. Lack of access to natural light can be linked to exhaustion and health issues amongst
                working personnel and detainees.</p>
