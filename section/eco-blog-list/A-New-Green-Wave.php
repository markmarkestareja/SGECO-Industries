            <p>BILL MCKIBBEN, an American environmentalist, once dismissed sustainability as “a buzzless buzzword”. That
                seems about right. A survey of 2,000 companies by the MIT Sloan Management Review and the Boston
                Consulting Group found that two-thirds of businesspeople thought social and environmental matters were
                “significant” or “very significant” but that only 10% thought they themselves were doing enough about
                it. </p>
            <p>That sense of disappointment should be no surprise. Sustainability can refer to anything from building
                wind farms to combating social inequality. The idea crops up everywhere from Starbucks to the
                deliberations of the United Nations (whose governments are in the middle of working out a set of
                so-called Sustainable Development Goals for 2015-30). An ill-defined, controversial notion is no basis
                for coherent policy. </p>
            <p>Many corporate “sustainability plans” are therefore modest. They focus on saving energy, cutting waste
                and streamlining logistics. Nothing wrong with that: these things reduce operating costs while
                benefiting the environment. They help explain why sustainability efforts tend to increase profits, not
                reduce them. A study by Robert Eccles and George Serafeim of the Harvard Business School (HBS) found
                that, between 1992 and 2010, companies which adopted what they call high-sustainability policies were
                more profitable and improved their stockmarket valuation more than those which did not (though this may
                just have been because high-sustainability firms happened to be better managed). </p>
            <p>However, there are drawbacks to such plans. For one thing, they are misnamed: these are efficiency
                policies, not sustainability ones. Companies ought to want to save energy or cut waste anyway,
                regardless of the impact on the environment. And it turns out that many of the schemes do not in fact do
                that much for the environment or social equity. The majority of greenhouse-gas emissions associated with
                consumer goods, for example, are produced either in the supply chain or by shoppers. So there is only
                limited scope for such products’ makers to lessen their environmental footprints through green measures
                of their own. </p>
            <p>As a result, most corporate sustainability plans rarely amount to more than cost-saving measures and
                compliance with government regulations, plus a few projects with a public-relations punch (say,
                reforesting parts of a cleared jungle). They fall well short of putting sustainability at the heart of
                what firms do. </p>
            <p>For some companies, though, that is changing. Take SABMiller, the world’s second-largest brewer. The firm
                has been a pioneer in the field. But until recently its sustainability efforts consisted of a laundry
                list of targets (there used to be ten) aimed at reducing carbon emissions or water usage in its brewing
                operations. This summer it unveiled new, broader targets—only five this time—which apply to suppliers,
                sellers and customers, as well as to SABMiller itself. It is promising to teach basic business skills to
                500,000 small enterprises, mostly shops which sell its beer. It is helping farmers use water more
                efficiently: in Rajasthan, in northern India, it is working with wheat farmers who have been depleting
                their aquifer to reduce water use by a quarter, to ensure it still has water to brew beer. And it is
                sponsoring anti-drunkenness and road-safety campaigns aimed at its own customers. </p>
            <p>Jane Nelson, director of the Corporate Social Responsibility Initiative at the Harvard Kennedy School,
                says SABMiller’s efforts are characteristic of a new wave of sustainability plans. These set targets not
                only for the company but for the people it works with and sells to. The targets are not only about the
                environment but society at large. (In a spectacular example, Unilever, an Anglo-Dutch consumer-goods
                giant, says it aims to “help a billion people take steps to improve their health and well-being”.) They
                are supervised by the board, not left to specialists. Domtar, an American fibre company, created a
                sustainability committee but the vice-president for sustainability does not chair it; the chair rotates
                among other managers so as to involve the firm as a whole. In short, she argues, for some companies
                sustainability has become a core part of their strategy, not just a green way to cut costs. </p>
            <h2>Little Green Men</h2>
            <p>But why should firms make sustainability central to what they do? Environmentalists might reply that
                virtue is its own reward. But companies need more concrete returns—higher profits, say, or increased
                sales, or higher stockmarket valuations. </p>
            <p>The first wave of sustainability policies provided those. The new wave may not: sustainability targets
                could raise costs, not cut them, making environmentally friendly consumer goods more expensive than the
                eco-hostile variety. Efforts to combat social inequality could boost wages. Training can be costly. </p>
            <p>Paul Polman, the boss of Unilever, argues that good sustainability policies still improve the
                fundamentals of businesses in the long run. They change customers’ behaviour in beneficial ways—by, say,
                increasing demand for green products that the firm makes. They also please investors concerned about
                environmental threats. The trouble is that consumer behaviour is often slow to change and that, if green
                products are too expensive, the firm risks losing market share. Environmental investors are still a
                minority among shareholders, most of whom continue to be more concerned about quarterly earnings. </p>
            <p>The first wave of sustainability rewarded itself. The new wave will not do that. It is more akin to
                investing now to have a licence to operate in future, when consumers, lobbyists and regulators will be
                ever more demanding about the way firms behave. That does not mean the new wave will not reward its
                adopters. But it will boost their long-term competitive position, rather than their short-term profits.
                Unlike the rewards of the superficial first wave, those of deeper sustainability could take years to
                sink in. </p>
