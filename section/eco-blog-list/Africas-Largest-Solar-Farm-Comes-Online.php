            <h2>Crazy Solar Power Plants</h2>
            <p>Renewable energy company SolarReserve, headquartered in Santa Monica, Calif., is one such place. This
                month they announced they had the Jasper solar farm, located near Kimberley in South Africa, running at
                full capacity. The 96 MW installation is Africa’s largest solar power project.</p>
            <p>About 325,000 photovoltaic modules will deliver 180,000 megawatt-hours of renewable electricity annually
                to region. That’s enough to power 80,000 homes.</p>
            <p>Like other countries around the world, South Africa is trying to reduce carbon emissions as well as
                increase renewable energy sources. They’ve set a goal of having 18 gigawatts of clean energy online by
                2030. The Jasper project is one such installation getting the country closer to its goal.</p>
            <h2>Solar-Powered Bulbs Brighten Off-Grid Homes</h2>
            <p>The Jasper project is one of a few big solar power plants coming online in Africa. In 2015, the
                155-megawatt Nzema project in Ghana will provide that country with electricity. And Morocco aims to
                build several solar energy plants that will generate 2,000 megawatts of electricity by the year 2020.
