        <div class="news-update-detail">
            <p>CERTIFIED ‘GREEN’ – Net Lima of The Net Group, a boutique office building located at Bonifacio Global
                City, is a 4-Star Building for Ecologically Responsive Design Excellence (BERDE) Project under the BERDE
                for New Construction version 1.0.0. It is the first certified green building under the BERDE Green
                Building Rating System, certified by TÜV Rheinland Philippines, Inc., a duly-accredited certification
                body of the Philippine Green Building Council (PHILGBC). (Photo courtesy of The Net Group)</p>
            <p>( Article first Published on: Manila Bulletin.com | November 25, 2014)</p>
            <p style="font-weight: 700; color: var(--dark-color);">For the past 30 years, Filipinos have been renewing
                their interest in constructing green buildings as they face more complex environmental problems. Taking
                advantage of the world’s most abundant and free energy sources are a priority factor in pursuing this
                cause. We can collaborate... visit our site www.eco.ph today!</p>
            <p>“Green buildings are new kinds of buildings that are environment-friendly. These are [structures] that
                consume less electricity and water, and produce less waste,” Philippine Green Building Council (PHILGBC)
                Chairman Christopher dela Cruz told the Manila Bulletin.</p>
            <p>Nowadays, green buildings utilize solar panels and consist of high-performance glass, which reduces the
                amount of heat entering the buildings, lessening the need for air-conditioners, he said.</p>
            <p>Other features he cited include eco-friendly air-conditioners, structures that can recycle used water,
                small-scale wind turbines, and green roofing.</p>
            <p>“We also look into heritage conservation, as a priority factor in constructing green buildings,” Dela
                Cruz said.</p>
            <p>Green buildings are now constructed using the modular method, which involves assembling large structural
                parts in modules or groups. Construction also generates less waste.</p>
            <p>Planning for green buildings involve full coordination among architects, engineers, contractors, and
                others, who must design structures with reducing pollution in mind.</p>
            <p>“Green builders” collaborate with not just the Department of Environment and Natural Resources, but also
                other government agencies, to meet compliance standards.</p>
            <p>“The construction of green buildings have created ‘green jobs,’ as new standards, products, and services
                arise,” dela Cruz said.</p>
            <p>In the country, many of these green buildings can be seen in Makati, Quezon City, Manila, Mandaluyong
                City, Taguig, as well as in Cebu City and Davao City.</p>
            <p>“As the Philippines currently has the highest electricity rates in Asia, businesses in the country treat
                electricity bills as among their major expenses,” Dela Cruz said. “This affects the competitiveness of
                our companies.”</p>
            <p>PHILGBC uses its own accreditation system called Building for Ecologically Responsive Design Excellence
                (BERDE) to enact voluntary standards, and certify buildings in the country.</p>
            <p>The Department of Public Works and Highways (DPWH) is currently drafting the Green Building Code, which
                will follow the National Building Code and its implementing rules and regulations.</p>
            <p>The proposed code will tackle energy efficiency, water and wastewater management, solid waste management,
                materials and site sustainability, and indoor environmental quality.</p>
            <p>If properly enforced, the said code will generate up to R35.2 billion in savings by 2030.</p>
