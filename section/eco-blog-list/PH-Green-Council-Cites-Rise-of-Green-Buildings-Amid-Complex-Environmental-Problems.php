        <h1 class="p-large">PH Green Council Cites Rise of ‘Green’ Buildings Amid Complex Environmental Problems</h1>
    </div>
    <div class="news-update-img-text">
        <div class="news-update-img"><img src="asset/img/resources-menu/eco-blog/limabuilding.webp" alt="limabuilding">
