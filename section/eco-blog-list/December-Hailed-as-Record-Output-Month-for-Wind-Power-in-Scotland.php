        <h1 class="p-large">December Hailed as Record Output Month for Wind Power in Scotland</h1>
    </div>
    <div class="news-update-img-text">
        <div class="news-update-img"><img src="asset/img/resources-menu/eco-blog/windenergy.webp" alt="windenergy">
        </div>
        <div class="news-update-detail">
            <p>(Article first Published on: news.stv.tv/Scotland | January 03, 2015)</p>
            <p style="font-weight: 700; color: var(--dark-color)">December was a record month for wind power in
                Scotland, according to environmentalists who have hailed 2014 as a "massive year" for renewable energy.
            </p>
            <p style="font-weight: 700; color: var(--dark-color)">Renewable energy is taking off around the world, see
                how you can benefit today from SG Eco's range of products which promote natural lighting and
                ventilation, visit our site at www.eco.ph</p>
            <p>The biggest day for output for wind was on December 10 when there was enough energy generated to supply
                6.34 million homes for the whole day, analysis from WWF Scotland showed. The charity said wind turbines
                generated enough power to supply over 100% of Scottish households on 25 out of the 31 days of December.
            </p>
            <p>Throughout the year wind provided enough power for the electrical needs of 98% of Scottish households,
                with solar power meeting two-thirds or more of household electricity or hot water needs, it added.</p>
            <p>Lang Banks, WWF Scotland's director, said: "Without doubt, 2014 was a massive year for renewables, with
                wind turbines and solar panels helping to ensure millions of tonnes of climate-wreaking carbon emissions
                were avoided.</p>
            <p>"With 2015 being a critical year for addressing climate change internationally, it's vital that Scotland
                continues to press ahead with plans to harness even greater amounts of clean energy.</p>
            <p>"December turned out to be a record-breaking month for wind power, with enough green energy generated to
                supply a record 164% of Scottish households with the electricity they need.</p>
            <p>"Even on calmer days, wind still supplied the equivalent of over a third of electricity needs of every
                home."</p>
            <p>Using data provided by WeatherEnergy, the charity said for homes fitted with solar photo-voltaic systems,
                there was enough sunshine in Aberdeen, Edinburgh, Glasgow or Inverness to generate an estimated 100% or
                more of the electricity needs of an average property during June and July and 60% or more in the same
                four cities during March, April, May, August and September.</p>
            <p>Karen Robinson, of WeatherEnergy, added: "We're famous in the UK for our obsession with the weather, but
                how often do we see it in a positive light? At a time when the world is desperately looking for
                low-carbon sources of energy, the data show that clean renewables are already playing a significant and
                growing role in Scotland's, and the rest of the UK's, overall energy mix. We just need to blow their
                trumpet a bit more.</p>
            <p>"Scotland is clearly leading the way when it comes to wind power. However, despite misconceptions,
                Scotland also has potential for sun-loving renewables too. The data clearly show that there's plenty of
                sunshine to meet a significant proportion of an average family's electricity needs for most months of
                the year - even during some of the winter months. With hundreds of thousands of roofs, it would make
                sense to tap more of the sun's power."</p>
            <p>SNP MSP Rob Gibson welcomed the findings and said: "Last year really was a massive year for renewable
                energy; these are very welcome figures which demonstrate that the Scottish Government's commitment to
                and investment in renewables are paying dividends.</p>
            <p>"It is clearer than ever that Scotland's renewable electricity generation will play a key part in keeping
                the lights on across the UK - and to keeping energy bills down.</p>
            <p>"With Scottish Government support our renewables industry is going from strength to strength - bringing
                jobs and investment to Scotland, reducing carbon emissions and performing a key role in meeting our
                energy needs. But there is always more that can be done."</p>
