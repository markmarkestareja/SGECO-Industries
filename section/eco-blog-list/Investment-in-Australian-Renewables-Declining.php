            <p>The Climate Council says foreign investors are going to other countries because Australia's government
                has no clear renewable energy policy.</p>
            <p>Australia has gone from "leader to laggard" in energy projects, it added.</p>
            <p>Another new report says Australia will need to raise its carbon emission reduction target to 40% by 2025.
            </p>
            <p>The damning report on the state of renewable energy, entitled Lagging Behind: Australia and the Global
                Response to Climate Change, said the country was losing out on valuable business.</p>
            <p>Investment that could be coming to Australia was going overseas "to countries that are moving to a
                renewables energy future", said Tim Flannery, one of the report's authors.</p>
            <p>He said most countries around the world had accelerated action on climate change in the last five years
                because the consequences had become more and more clear.</p>
            <p>The report found China had retired 77 gigawatts of coal power stations between 2006 and 2010 and aimed to
                retire a further 20GW by next year.</p>
            <p>It also said the US was "rapidly exploiting the global shift to renewable energy" by introducing a range
                of incentives and initiatives to investors.</p>
            <p>The future of Australia's renewable energy industry remains highly uncertain, the report concluded,
                because of a lack of clear federal government renewable energy policy.</p>
            <p>"Consequently investment in renewable energy in 2014 has dropped by 70% compared with the previous year,"
                it said.</p>
            <p>'A high risk approach'</p>
            <p>The second new report, by the Climate Institute, calls on Australia's government to announce an
                "independent, transparent" process for setting the post 2020 carbon emission reduction targets.</p>
            <p>Erwin Jackson, deputy chief executive of the climate body, said too much of the political debate had
                "ignored growing scientific, investment and international realities".</p>
            <p>"This short-term focus is simply a high risk approach to the significant challenges of decarbonising our
                economy and helping avoid dangerous impacts for Australia," he said.</p>
            <p>Prime Minister Tony Abbott is under pressure to cut the country's emissions much further than the
                government has planned after the European Union moved to set a new target of 40% by 2030.</p>
            <p>The EU said the agreement, which includes a 27% target for renewable energy by 2030, should set a new
                global standard.</p>
            <p>Mr Abbott's government has said it will discuss a post-2020 target early next year and it is likely to
                come under more pressure this weekend at the G20 summit, which is being held in Brisbane.</p>
