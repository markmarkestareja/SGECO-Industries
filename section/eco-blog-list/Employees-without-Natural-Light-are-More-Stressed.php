        <h1 class="p-large">Employees without ‘Natural Light’ are More Stressed</h1>
    </div>
    <div class="news-update-img-text">
        <div class="news-update-img"><img src="asset/img/resources-menu/eco-blog/office.webp" alt="office"></div>
        <div class="news-update-detail">
            <p>(Article First Published on: humanresourcesonline.net | April 01, 2015)</p>
            <p>Want to reduce your team’s stress levels? Try giving them a seating spot with more access to natural
                light.</p>
            <p>Echoing earlier reports, a new study has found employees who work in environments with natural elements
                such as light and green plants are more efficient and happier.</p>
            <p>Polling 7,600 office workers from 16 countries, The Human Spaces global study highlighted staff with
                access to nature reported a 15% higher level of well being, are 6% more productive and 15% more creative
                overall.</p>
            <p>Unfortunately however, nearly half (47%) of office employees worldwide stated they have no natural light
                in their working environment, and almost two thirds (58%) have no live plants in their workspace.</p>
            <p>In Canada, 32% of workers reported having no windows. This was closely followed by Australia and the
                U.S., with 28% and 27% of workers respectively.</p>
            <p>Interestingly, all three countries reported above average levels of stress.</p>
            <p>Conversely, workers in Indonesia and India reported some of the highest levels of light and space at 93%
                and 92%, respectively, and reported some of the lowest levels of unhappiness.</p>
            <p>It was, therefore, unsurprising that natural light was chosen by employees as the most wanted element in
                their offices. This was followed by live indoor plants, and a quiet working space.</p>
            <p>A view of the sea and being surrounded by bright colours rounded up the top five.</p>
            <p>“The benefit of design inspired by nature, known as biophilic design, is accumulating evidence at a rapid
                pace,” said organisational psychologist Professor Sir Cary Cooper, who led the study.</p>
            <p>Indeed, office design was so important to workers that a third of global respondents stated it would
                unequivocally affect their decision whether or not to work somewhere.</p>
            <p>Office design was especially vital in India (67%), Indonesia (62%) and the Philippines (60%).</p>
