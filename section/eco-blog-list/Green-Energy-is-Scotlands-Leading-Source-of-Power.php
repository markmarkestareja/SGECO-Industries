            <p>(Article first Published on: scotsman.com | November 27, 2014)</p>
            <p>Climate campaigners yesterday welcomed the figures, saying they mark a “crucial tipping point” and signal
                the “beginning of the end” for fossil fuels and nuclear power.</p>
            <p>The latest energy trends report from the Department of Energy & Climate Change (DECC) shows renewables
                generated 32 per cent more electricity than any other single source of power in Scotland in the first
                half of this year.</p>
            <p>The sector – including solar, wind, hydro and biomass energy sources – produced a record 10.3
                terawatt-hours of power. This compares to 7.8TWh from nuclear, 5.6TWh from coal and 1.4TWh from
                gas-fired power stations in the same period. Nuclear was previously the nation’s primary source of
                electricity.</p>
            <p>Dr Richard Dixon, director of Friends of the Earth Scotland, said: “We have joined the pioneer nations
                who are leading the way to a 100 per cent renewables, zero-carbon world. Becoming the largest single
                source of electricity in Scotland is a tremendous milestone on the way to meeting all of our electricity
                demand from green energy sources in just six years’ time.”</p>
            <p>WWF Scotland director Lang Banks said: “Last month, while nuclear reactors were forced to shut because of
                cracks, Scotland’s renewables were quietly and cleanly helping keep the lights on in homes across the
                country.</p>
            <p>“Wind turbines in Scotland alone generated enough electricity to supply three million homes in the UK –
                equivalent to 126 per cent of the electricity needs of every home north of the Border.”</p>
            <p>However, last night Linda Holt, spokesperson for Scotland Against Spin, said: “Wind energy is
                intermittent and uncontrollable, and cannot be relied upon to provide either baseload or despatchable
                generation. Without large-scale storage capacity – which does not exist – wind can never be the mainstay
                of any country’s domestic electricity consumption. The more wind is added to the energy mix, the more
                expensive electricity becomes because of the need for back-up, balancing and grid expansion. As those
                6.3TWh of wind-generated electricity cost millions in subsidies, they are directly responsible for
                plunging Scots into fuel poverty.”</p>
            <p>Scottish Labour leadership contender Neil Findlay, MSP for Lothian and a long-standing critic of
                government renewable energy policies, said: “I am not against renewable energy but before we rush to
                applaud this report we need to face up to two major criticisms.</p>
            <p>“Firstly, what we have is a lack of co-ordinated approach, with communities inundated by speculative
                applications from developers. Secondly, it is the corporations and venture capital firms which often
                benefit from these enterprises. For them it is just another method of financial speculation.”</p>
            <p>Niall Stuart, chief executive of industry body Scottish Renewables, said: “Every unit of power generated
                from renewables means less carbon emitted from the burning of fossil fuels, decreases our reliance on
                imported energy and supports jobs and investment in communities.”</p>
            <p>Energy minister Fergus Ewing said: “It is vital that appropriate support for renewables in Scotland is
                maintained following the introduction of electricity market reform in the UK.”</p>
            <p>The figures emerged days after a Scottish wave energy firm announced it was going into administration.
                Pelamis Wave Power, which invented the “sea snake” device, took the decision after failing to raise
                funds needed to develop the technology.</p>
