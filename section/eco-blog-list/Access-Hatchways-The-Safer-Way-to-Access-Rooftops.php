        <div class="news-update-detail">
            <p>Roof works always involve risk and potential injuries especially if you are not using the right equipment
                for roof access.</p>
            <p>According to the Occupational Safety and Health Administration (OSHA), more than 100,000 workers in the
                United States are injured annually due to falls on construction sites.</p>
            <p>In order to avoid becoming a victim, installing a safe access system to rooftops is one of the best
                solutions.</p>
            <p>SG Eco’s Roof Access Hatchways provide the safest and most convenient entry to your roof. These hatchways
                are ideal for domestic and commercial buildings.</p>
            <div class="skylight-bullets-container">
                <div class="skylight-bullets-title">
                    <h3>Falling from Ladders</h3>
                </div>
                <p>This is one of the leading causes of fatalities whether on occupational or non-occupational
                    activities. It can happen due to various reasons: over-balancing, unstable footing or soft ground,
                    defective or loose ladder components etc. </p>
                <p class="note">Fall-off injuries related to ladder can be substantially reduced with the use of Access
                    Hatchways. This product allows workers or residents to safely access their roofs with its Gapseal
                    Foam, sealing and supporting its lid to prevent any movement especially during strong winds.</p>
            </div>
            <div class="skylight-bullets-container">
                <div class="skylight-bullets-title">
                    <h3>Getting trapped or crushed between MEWPs</h3>
                </div>
                <p>Mobile Elevating Work Platforms (MEWPs) are machinery or equipment that is in different jobs that
                    require working at heights such as tree cutting/trimming and roof work. </p>
                <p>The use of MEWPs can reduce the time and effort of workers but inadequate knowledge on how to operate
                    these machines can also lead to serious injuries such as entrapment and collision of the equipment
                    with adjacent structures.</p>
                <p class="note">Access Hatchways no longer require additional machinery or equipment in order to gain
                    access to your roof. It is manufactured from 0.75mm sheet metal for durability. Its design also
                    offers ease of use to customers and is suitable for most roof type.</p>
            </div>
            <div class="skylight-bullets-container">
                <div class="skylight-bullets-title">
                    <h3>Risk of Falling Objects</h3>
                </div>
                <p>Accidents due to falling objects which can lead to injury or death to workers and even by-passers or
                    onlookers can be prevented if you have a safer access system to your roof.</p>
                <p class="note">Aside from the padlockable latch from the inside which provides additional security
                    against unwanted intrusion, Dome Lid Access Hatchways also allows natural light to enter the
                    building thereby improving the ambient lighting within the building.</p>
