            <p>The UK is on track to meet its renewable energy goals, with wind power substituting for gas and coal use
                and driving down greenhouse gas emissions, according to new analyses. However, the actions of the next
                government are likely to be crucial in deciding whether the legally binding targets can be met.</p>
            <p>Gas use in the UK fell by more than a fifth from 2005 to 2012, as energy efficiency increased across the
                economy and green energy took up more of the burden.</p>
            <p>Under European Union targets, the UK must produce 15% of its energy from renewable sources by 2020, and
                is one of a small number of big member states to be judged on track to meet all of its energy and
                climate commitments by the European environment agency.</p>
            <p>This was confirmed on Thursday by the Office for National Statistics, which found that 15% of the UK’s
                electricity came from renewable sources in 2013. This puts the UK about halfway towards its commitments,
                because the overall energy target includes transport and heating, as well as electricity generation. For
                the UK to meet its EU goals, electricity generation from renewable sources is likely to have to increase
                to above 30% by 2020.</p>
            <p>Gas dominates the UK’s domestic heating supply, and for most of the past two decades has been the main
                source of electricity generation. But this situation has reversed in the last three years, with gas use
                falling sharply and the slack taken up by ageing coal-fired power stations, now the biggest source of
                the UK’s electricity generation. This is owing to a combination of factors, including a very low price
                on carbon dioxide emissions under the EU’s carbon trading scheme (a high price was intended to
                discourage coal use) and the knock-on effects of the shale gas boom in the US, where cheap gas use has
                soared creating a glut of cheap coal on the international market. Gas in the UK has remained more
                expensive, as North Sea supplies have been rapidly depleted.</p>
            <p>The rise in renewables while gas use fell also highlights the competition that clean energy represents to
                gas. Gas companies have been keen to emphasise the fuel as a “greener” alternative to coal – it burns
                more cleanly, producing much less carbon dioxide and none of some other pollutants associated with coal
                – and as a “transition” fuel that can help the move to a low-carbon economy alongside the use of
                renewable.</p>
            <p>However, many in the green sector are concerned that investment in renewable alternatives could suffer if
                gas is prioritised. Many of Europe’s biggest players in renewable energy are power companies that still
                generate large amounts of their output from fossil fuels.</p>
            <p>Renewable UK, the trade association for the wind industry, said renewable power generators were “doing
                their bit” towards the UK’s targets, but that fossil fuel use in transport and heating remained
                relatively high. For renewables to cut transport emissions too, through electric cars, the next
                government needs to show support for wind power, they said.</p>
            <p>Gordon Edge, Renewable UK’s director of policy said: “Onshore and offshore wind farms have been growing
                rapidly and are now generating more than half of our clean electricity. The question is whether the UK
                will make fast enough progress on renewable heat and renewable transport as well – that’s looking less
                certain. If there’s a shortfall in those areas, we’ll need to generate more renewable electricity to hit
                the target.</p>
            <p>“The cheapest way to do this would be to install more onshore wind, which is why it’s utterly baffling
                that the Conservative party is proposing to cap the development of onshore wind if they’re elected in
                May.”</p>
            <p>He added that meeting the legally binding goal would require more effort: “Whichever party is in
                government next, it looks likely that they’ll need to consider an even more rapid scaling up in the
                generation of renewable electricity than currently planned over the next five years. Onshore and
                offshore wind are poised to step up and meet that demand but we’ll need the new government to set more
                ambitious targets early on, in terms of how much wind they want to see installed, or the UK will risk
                falling short of the overall target.”</p>
