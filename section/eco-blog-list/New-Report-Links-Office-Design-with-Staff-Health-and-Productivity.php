            <h2>Summary of Evidence</h2>
            <p>Indoor air quality: A comprehensive body of research suggests that better indoor air quality (low
                concentrations of CO2 and pollutants and high ventilation rates) can lead to productivity improvements
                of 8-11%.</p>
            <p>Thermal comfort: Research demonstrates that thermal comfort has a significant impact on workplace
                satisfaction and modest degrees of personal control over thermal comfort can return single digit
                improvements in productivity.</p>
            <p>Lighting and views of nature: Several studies have estimated productivity gains as a result of proximity
                to windows, with experts now thinking that views from windows are probably the more significant factor,
                particularly where the view offers a connection to nature.</p>
            <p>Noise and acoustics: Research suggests that being productive in the modern knowledge-based office is
                practically impossible when noise provides an unwanted distraction. This can be a major cause of
                dissatisfaction amongst occupants.</p>
            <p>Interior layout: The way the interior of an office is configured (including workstation density and
                configuration of work space, breakout space and social space) has been found to have an impact on
                concentration, collaboration, confidentiality and creativity.</p>
            <p>Active design and exercise: Health can be improved through exercise, and so active design within a
                building, and access to services and amenities such as gyms, bicycle storage and green space can help to
                encourage healthier lifestyles of building occupants.</p>
            <h2>Toolkit to measure health, wellbeing and productivity</h2>
            <p>Financial metrics: Absenteeism, staff turnover, revenue breakdown (by department or per building),
                medical costs and complaints, and physical complaints.</p>
            <p>Perceptual metrics: Studies which test a range of self-reported attitudes into health, wellbeing and
                productivity in the workplace can contain a wealth of information for improving office performance.</p>
            <p>Physical metrics: Direct measures of the physical office environment, such as temperature, are key to
                measuring the effect on the health, wellbeing and productivity of workers. Exciting developments in this
                area such as portable and wearable technology are likely to substantially expand our understanding.</p>
