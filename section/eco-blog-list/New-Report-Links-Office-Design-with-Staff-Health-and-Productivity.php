            <p>(Article first published on: worldgbc.org |September 24, 2014)</p>
            <p style="font-weight: 700; color: var(--dark-color);">Another recent study shows how a well-designed office
                can improve employees’ productivity inside the building… World GBC finds that a range of factors – from
                air quality and lighting, to views of nature and interior layout – can affect the health, satisfaction
                and job performance of office workers. For natural lighting and ventilation system, check out our site
                at <a href="http://www.eco.ph/">http://www.eco.ph/</a></p>
            <p>A new report from the World Green Building Council (World GBC) finds “overwhelming evidence” that office
                design significantly impacts the health, wellbeing and productivity of staff.</p>
            <p>Health, Wellbeing and Productivity in Offices: The Next Chapter for Green Building finds that a range of
                factors – from air quality and lighting, to views of nature and interior layout – can affect the health,
                satisfaction and job performance of office workers.</p>
            <p>The report – sponsored by JLL, Lend Lease and Skanska – also presents a simple toolkit that businesses
                can use to measure the health, wellbeing and productivity of their buildings and inform financial
                decision-making.</p>
            <p>Understanding the link between workers and their workplace helps to drive the business case for higher
                quality, healthy and greener buildings, valued by investors, developers and tenants alike.</p>
            <p>With salaries and benefits typically responsible for 90 percent of an organization’s expenditure, any
                higher construction or occupation costs are far outweighed by even small improvements in staff
                performance.</p>
            <p>Jane Henley, CEO of the World Green Building Council, said: “The evidence linking good office design and
                improved health, wellbeing and productivity of staff is now overwhelming. There is unquestionably a
                clear business case for investing in, developing and occupying healthier, greener buildings.</p>
            <p>“Most businesses are already sitting on a treasure trove of information that can have an immediate impact
                on their two biggest expenses – people and buildings. Understanding the relationship between the two can
                help businesses achieve significant competitive advantage.”</p>
            <p>Claudia Hamm, Head of Strategic Workplace (EMEA) at JLL, said: “Major corporate clients are now
                recognizing the business benefits and productivity gains of buildings which bring out the best in their
                employees and are increasingly making their strategic real estate decisions with these in mind. This
                report reinforces the view that a building’s impact on its occupants must be included within financial
                considerations.”</p>
            <p>Geoff Dutaillis, Group Head of Sustainability at Lend Lease, said: “Whatever business you are in, you are
                in the business of people. How a building ‘works for people’ should be the priority question. This
                report provides further evidence that workplaces with clean air, natural daylight and engaging and
                adaptable layouts all contribute to making healthier, happier and more motivated individuals who create
                stronger, more resilient and profitable companies.”</p>
            <p>Staffan Haglind, Green Business Officer at Skanska, said: “The equation for our clients is very simple: a
                small percentage improvement in the health and productivity of your staff far outweighs any additional
                costs associated with commissioning or occupying a greener, healthier office. Giving employees the best
                possible conditions to perform and stay healthy is not only wise from a financial perspective, it’s just
                the right thing to do.”</p>
            <p>Health, Wellbeing and Productivity in Offices builds upon the 2013 World GBC report The Business Case for
                Green Building which featured a chapter on the health and productivity benefits of green buildings.</p>
            <p>The report will be launched in London on 24 September as part of World Green Building Week. Global launch
