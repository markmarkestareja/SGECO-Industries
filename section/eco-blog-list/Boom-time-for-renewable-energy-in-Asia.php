            <p>From ultra-fast-charging batteries in Singapore to solar farms in Thailand, demand for and use of
                renewable energy is set to rise in fast-growing Asia.</p>
            <p>Industry leaders speaking at the Asia Clean Energy Summit note that with such growth, business
                opportunities are emerging across all aspects of the renewable sector from procurement and construction
                services to sensors for data analytics.</p>
            <p>Bernard Blez, senior vice president of R&D at French utility firm GDF Suez, noted that for the next ten
                years, growth in Asia will account for 65 percent of growth in energy consumption worldwide. The push by
                many Asian governments to improve air quality by switching from coal to gas and renewables is another
                key driver, he said.</p>
            <p>Utility firms will have to respond to the rise of renewables in the region by working out how to rapidly
                develop centralised power plants, as well as come up with new business models for decentralised,
                distributed power generation, added Blez.</p>
            <p>Fellow panellist Dr. Bartosz Wojszczyk, chief innovation officer at the Philippines’ largest electricity
                distributor Meralco, said the growth of renewables would occur “whether we want it or not; the question
                is how do we make this attractive in a controlled way.”</p>
            <p>The Philippines, Wojszczyk explained, faces plenty of power-related challenges such as dispersed islands,
                typhoons and monsoons. Furthermore, some 30 percent of its population still lacks access to electricity.
                In 2015, there is likely to be a power generation deficit. “Solar and wind will probably be a big
                opportunity for us,” he said.</p>
            <h2>Bullish on wider energy sector</h2>
            <p>Panellists also identified other business opportunities in the wider energy sector.</p>
            <p>Manish Kasliwal, head of the smart energy business incubation centre at technology services provider NEC
                APAC, noted that in the commercial and industrial sector, users were still struggling to map their
                energy usage patterns and work out how to control energy consumption.</p>
            <p>Start-ups could tap and analyse this data, learn from it, and implement those lessons as a service to
                bigger enterprise, he suggested.</p>
            <p>Micro-grids for islands and remote areas were also a potential area. For instance, many islands in the
                Philippines rely on pricey diesel generation at US$0.40 to $0.50 per kilowatt-hour and conventional
                centralised power generation would require expensive transmission lines to remote parts of Australia.
                Renewable energy would be cost-competitive in both places, said panellists.</p>
            <p>New technologies for energy storage were another. Where renewable energy is variable or intermittent,
                such as solar or wind, storage is needed to smooth out minute-to-minute fluctuations or to shore up
                power for later use.</p>
            <p>To test-bed the development and integration of such technologies, Singapore’s Nanyang Technological
                University is setting up a demonstration micro-grid at the offshore island of Semakau to integrate
                solar, wind, and tidal generation with more experimental energy storage and power-to-gas technologies.
            </p>
            <h2>Asia leads in solar energy</h2>
            <p>Asia is also leading in the development of solar photovoltaics, said Dolf Gielen, director at the
                International Renewable energy Association.</p>
            <p>In 2013, China added 13 GW of solar capacity while India added 1 GW – enough to power some 250,000
                four-room flats.</p>
            <p>And Singapore and other countries in the region are seeing the rise of new business models.</p>
            <p>Online solar marketplace SolarPVExchange, launched here in June, consolidates information from more than
                20 solar installers to help potential buyers in Singapore and Malaysia to estimate the effectiveness and
                cost of installing solar panels.</p>
            <p>Managing director of integrator Phoenix Solar, Christophe Inglin, said solar leasing – where users do not
                own the panels but leases them from a company that sells them electricity at favourable rates - is just
                a stepping-stone for many more business models to come.</p>
            <p>Others might include crowd-funding, which would function much like a bond that pays interest to retail
                investors; and a car-leasing model in which the manufacturers themselves lease solar panels and systems,
                he said.</p>
            <p>But the key is to eliminate feed-in tariffs and let renewables be cost-competitive on their own. In
                Singapore there are no subsidies or feed-in tariffs where government agencies pay producers a favourable
                rate for solar energy, while in the Philippines solar is competitive against expensive diesel
                generation. “Assuming we don’t need subsidies, market innovation can take place,” Inglin added.</p>
            <p>And the most important thing that governments can do to encourage the growth of renewables is “clarity,
                clarity, clarity” of incentives and policies, said Maxine Ghavi, head of the solar initiative at power
                and automation firm ABB.</p>
            <p>Too often, fossil fuels are subsidised and electricity prices regulated so there is no push for users to
                transition to renewables, she said.</p>
