            <p>GENEVA, Switzerland (UPDATED) – Surging carbon dioxide levels boosted greenhouse gases in the atmosphere
                to a new high in 2013, amid worrying signs that absorption by land and sea is waning, the UN warned
                Tuesday, September 9. </p>
            <p>"An alarm bell is ringing," Michel Jarraud, head of the World Meteorological Organization (WMO), told
                reporters in Geneva. </p>
            <p>In its annual report on Earth-warming greenhouse gases in the atmosphere, the UN agency said
                concentrations of carbon dioxide (CO2), methane and nitrous oxide all broke records in 2013. </p>
            <p>"We know without any doubt that our climate is changing and our weather is becoming more extreme due to
                human activities such as the burning of fossil fuels," Jarraud said. </p>
            <p>"We must reverse this trend by cutting emissions of CO2 and other greenhouse gases across the board," he
                said in a statement, and warned: "we are running out of time."</p>
            <p>Especially worrying, Jarraud said, was the sharp rise in CO2, by far the main culprit in global warming,
                to 396 parts per million in the atmosphere last year.</p>
            <p>That was 142% of levels prior to the year 1750, and marked a hike of 2.9 parts per million between 2012
                and 2013 – the largest annual increase in 30 years.</p>
            <p>It was not clear why concentrations rose so sharply, but Jarraud suggested it could be due to a shift in
                the ability of oceans and the biosphere to absorb emissions.</p>
            <p>'A worrying signal'</p>
            <p>Oceans swallow about a quarter of greenhouse gas emissions, while the biosphere sucks up another quarter,
                so any change "could potentially have big consequences," he warned.</p>
            <p>"Clearly now we have a signal, ... a worrying signal," said Jarraud.</p>
            <p>University of Reading meteorology professor William Collins said the WMO's suggestion that the biosphere
                may be removing less CO2 as the climate warms was credible, and implied a "future amplification of
                climate change".</p>
            <p>"We can't expect to benefit from this natural removal for ever," he warned.</p>
            <p>Tuesday's report came ahead of a September 23 summit called by UN Secretary General Ban Ki-moon to try
                and build momentum ahead of the 2015 deadline for a historic climate deal to be signed in Paris, to take
                effect from 2020.</p>
            <p>The UN is seeking to limit global warming to two degrees Celsius (3.6 degrees Fahrenheit) over
                pre-Industrial Revolution levels, but scientists say that on current emission trends, temperatures could
                be double that by century's end.</p>
            <p>"We have the knowledge and we have the tools for action to try to keep temperature increases within two
                degrees Celsius to give our planet a chance and to give our children and grandchildren a future,"
                Jarraud said, insisting that "pleading ignorance can no longer be an excuse for not acting".</p>
            <p>Professor Dave Reay, chair in carbon management at the University of Edinburgh, reacted to the report
                with dismay.</p>
            <p>"This is the litmus test when it comes to our efforts to reduce emissions and on this evidence we are
                failing," he said.</p>
            <p>The findings are especially worrying since CO2 remains in the atmosphere for hundreds of years and in the
                oceans for even longer.</p>
            <p>While the ocean's absorption of CO2 helps limit global warming, "the bad news is that it contributes to
                the acidification of the ocean," Jarraud said.</p>
            <p>Increased acidity not only alters the ocean's ecosystem, but can also reduce its ability to absorb more
                CO2, he said.</p>
            <p>Every day the world's oceans absorb some four kg (8.8 pounds) of CO2 per person, the WMO said, adding
                that ocean acidification levels were "unprecedented at least over the last 300 million years".</p>
            <p>And things will only get worse, said Jarraud.</p>
            <p>"Past, present and future CO2 emissions will have a cumulative impact on both global warming and ocean
                acidification," he said, adding that "the laws of physics are non-negotiable". – Rappler.com</p>
