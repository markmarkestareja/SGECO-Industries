        <h1 class="p-large">Data shows efficient energy saved 250m</h1>
    </div>
    <div class="news-update-img-text">
        <div class="news-update-detail">
            <p>The UK economy saved nearly £250m in fuel costs last year by generating its energy more efficiently,
                Government figures show.</p>
            <p>This saving is equivalent to the gas bills of more than 350,000 homes.</p>
            <p>The Digest of UK Energy Statistics, published annually by DECC, reported an increase in combined heat and
                power plants, with 54 new schemes built in 2014.</p>
            <p>However, some industrial sectors saw limited new investment and some key industrial sectors saw
                significant reductions in CHP capacity and generation.</p>
            <p>ADE director Dr Tim Rotheray said: “There are hundreds more commercial and industrial sites that could
                benefit from generating their own heat and power locally by putting the right policy framework in place.
            </p>
            <p>“A welcome tax relief implemented in 2015 is key to protecting existing industrial efficiency
                investments. The Government’s forthcoming Carbon Taxation review now presents a major opportunity to
                unlock the untapped efficiency opportunity, boost energy productivity and support UK business
                competitiveness.”</p>
