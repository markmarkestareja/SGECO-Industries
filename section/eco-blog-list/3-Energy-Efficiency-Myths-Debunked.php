            <h2>Common misconceptions about efficiency not only can increase energy use, but actually can end up costing
                consumers and business money.</h2>
            <p>We all think we know about energy efficiency. We make an effort to turn off the lights when we leave the
                room and close the refrigerator door after removing food. In today’s society, it is more important than
                ever before to start cracking down on energy use to save both money and the environment.</p>
            <p>Many initiatives are in place to help reduce energy use, including regulations from the EPA to save
                billions on energy bills and reduce the need for new power supplies. Additionally, technology is
                constantly advancing, which allows society to better understand what is needed to improve and monitor
                energy use.</p>
            <p>With all of these tools at our disposal, are consumers and businesses taking the right steps to become
                more energy efficient? From using less energy to energy audits to the cost dilemma, below are three
                common misconceptions that should be debunked.</p>
            <h2>Myth 1: Using less energy is the same as being energy-efficient.</h2>
            <p>Fact: Energy conservation means using less energy. Energy efficiency means using energy more
                productively.</p>
            <p>People often struggle to grasp what energy efficiency is, at its core. Too often, people interpret it as
                slightly reducing comfort or quality of life, which can be a deterrent for some.</p>
            <p>In reality, energy efficiency means “getting the same output with less input.” It means that energy
                should be used in a more productive manner, meaning we get more for what is used. While actions such as
                turning off lights or turning down the heat do use less energy, this is known as energy conservation,
                not energy efficiency.</p>
            <p>While both energy conservation and energy efficiency play a role in reducing energy consumption, it is
                important to distinguish between the two and note that consumers do not need to sacrifice comfort or
                quality of living (as is common to energy conservation measures) to be energy efficient.</p>
            <div class="skylight-bullets-container">
                <p class="note" style="margin-left: 0;">Turning off the lights when you leave the room is a good
                    practice, but it's not an example of energy efficiency.</p>
            </div>
            <h2>Myth 2: Energy audits are the best way to become more energy efficient.</h2>
            <p>Fact: Energy audits are a good tool when approached correctly, but are often overwhelming and confusing.
                Energy audits have become a common practice, whether at home or in an office building. Third party
                auditors come in to examine the office or home, the equipment, the insulation and other aspects to see
                where improvements can be made to make the home or office more efficient. But with all the time and
                investment required to complete an energy audit, is it truly the best option to make sure buildings are
                more energy efficient?</p>
            <p>Standalone energy audits without the proper planning and follow-up are similar to walking into a
                restaurant, asking for a table, sitting down and receiving your menu — and then leaving without your
                meal. You know the menu, but you’re still hungry. When an energy audit is conducted without a clear goal
                in mind, it can leave consumers and businesses with a list of to-dos and possibilities, but no tangible
                outcome or actions. In many cases, too many options — lighting, window tinting, adjusting overall
                behavior — can be overwhelming and ultimately prevent companies from getting started.</p>
            <p>Energy audits can be valuable, as long as consumers and building owners in offices and industrial
                settings alike are clear about overall objectives. This not only cuts down on confusion in the aftermath
                of an audit and makes it easier to take action, but also can affect the results of the audit.</p>
            <p>Ask yourself: What are you really after? Improved productivity? Increased comfort? Cost savings? Upgraded
                day lighting? A clearly outlined objective is where many companies and consumers fall short. Once you
                define this objective, a more tailored audit can be conducted that clearly identifies ways that energy
                efficiency as a solution can be crafted to meet that objective.</p>
            <div class="skylight-bullets-container">
                <p class="note" style="margin-left: 0;">An energy audit needs to plug into the customer's needs and
                    goals for the workplace.</p>
            </div>
            <h2>Myth 3: Energy efficiency is expensive.</h2>
            <p>Fact: Energy efficiency is an investment, not an expense.</p>
            <p>When consumers or businesses are asked why they haven’t taken steps to become more energy efficient, the
                answer is often because it is considered too expensive. In my opinion, this is the largest energy
                efficiency myth there is.</p>
            <p>It’s also the most difficult myth to debunk.</p>
            <p>The unfortunate fact is that while turning off your lights — energy conservation — is free, upgrading
                your air conditioning or heating system is not. However, it is important to understand the differences
                between long-term and short-term costs when considering energy efficiency.</p>
            <p>Consider the LED light bulb, which has been a huge help in debunking this myth. While more costly than a
                regular light bulb, it lasts longer and consumes energy more productively, therefore reducing the cost
                to provide light. While the initial cost is higher, the long-term cost is significantly smaller.</p>
            <p>The same is true for other energy efficiency measures. By considering the long-term costs, energy
                efficiency becomes an investment, rather than an expense. By changing our mindset to more closely
                reflect this view of energy efficiency, the upfront cost becomes more palatable to many.</p>
            <p>These are only a few of many myths around energy efficiency today. Once you grasp the difference between
                energy efficiency and energy consumption, the long-term investment of energy efficiency and then clearly
                outline an objective to improve energy use, a more energy efficient environment soon will follow.</p>
