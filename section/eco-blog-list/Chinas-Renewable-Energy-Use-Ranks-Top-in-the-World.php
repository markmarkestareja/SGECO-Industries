            <p>(Article First Published on: news.asiaone.com | January 18, 2015)</p>
            <p>China’s investment in renewable energy hit a record high of US$89.5 billion in 2014. This clearly shows
                the country’s vigorous efforts to cut down their energy expenses through its natural sources. Join the
                drive toward a clean energy, see how our products can contribute: www.eco.ph</p>
            <p>China ranks the top in the world in terms of the use of renewable energy with the increasing switch to
                renewable energy resources, said senior official on Saturday.</p>
            <p>China's investment in clean energy in 2014 hit a record US$89.5 billion (S$118.7 billion), accounting for
                29 per cent of the world's total.</p>
            <p>China's renewable energy generation capacity reached 430 million kilowatts by the end of 2014, accounting
                for 32 per cent of the country's total power capacity, said Shi Lishan, deputy director general of the
                New and Renewable Energy Department of the National Energy Administration during the fifth session of
                the International Renewable Energy Agency Assembly held in Abu Dhabi.</p>
            <p>According to Shi, China's renewable power generation was 1.2 trillion kilowatt-hours in 2014, accounting
                for 22 per cent of the country's total power consumption in the last year.</p>
            <p>China became a member of IRENA in January 2013, a milestone in international efforts to double the share
                of renewable energy worldwide by 2030.</p>
            <p>Shi said China will strengthen communication on projects and technology in renewable energy industries
                with other member countries and regions.</p>
            <p>"China will also make efforts to support underdeveloped countries' renewable energy development," Shi
                said.</p>
            <p>Adnan Amin, director-general of IRENA, said China's renewable power generation costs including that of
                solar and wind energy have significantly reduced, which will help the country to improve its energy
                structure in the long run."</p>
