            <p>If you worry about the initial energy and maintenance costs of upgrading your ventilation system, Green-vent Wind driven ventilator uses no energy and also requires no maintenance, so the calculation of the cost benefit only needs to include the initial cost of the installation.</p>

            <h2>Health Wise Internal Environment</h2>
            <p>A good ventilation system also removes airborne pollutants such as smoke, dust, poisonous gases & fumes from machinery or vehicles that can also help improve the health of the occupants inside the building</p>
            <h2>Increased Energy Efficiency of the Building</h2>
            <p>Excessive heat load on air conditioning ductwork caused by hot air trapped under the roof can cause air conditioners to work longer and harder thus leading to extra energy costs. Green-vent Solar reduces the ceiling temperature without the use of mains electricity.</p>
            <h2>Noiseless Operation</h2>
            <p>The Green-vent Solar utilizes a high performance 38V motor that generates very little noise.  Coupled with the fact that it is installed on the roof, in most installations you will never hear it operating.</p>

