            <p>(Article First Published on: farmfutures.com | March 16, 2015)</p>
            <p>USDA will now accept and review Rural Energy for America loan and grant applications year-round.</p>
            <p>USDA has expanded the application and review window for Rural Energy for America grant and loan
                applicants, as well as provided more stable funding for the program through the 2014 Farm Bill, Ag
                Secretary Tom Vilsack said Tuesday.</p>
            <p>"In the past, we've had to be concerned about appropriations processes that can change [program funding]
                year to year," Vilsack said, noting that the REAP funding is now tied to the life of the 2014 Farm Bill.
            </p>
            <p>The REAP program offerings allow small businesses and farmers to purchase and install renewable energy
                systems or make energy efficiency improvements. Vilsack said this not only helps farmers and small
                business cut energy costs, it also cuts carbon pollution and promotes renewable energy and jobs.</p>
            <p>"It's also a job creator," Vilsack said, noting that installers, solar panel producers and other
                construction employment opportunities are boosted by producers' uses of funding. More than $280 million
                is now available to eligible applicants through REAP.</p>
            <p>Grants will be available for up to 25% of total project costs and loan guarantees for up to 75% of total
                project costs for renewable energy systems and energy efficiency improvements.</p>
            <p>Eligible renewable energy projects must incorporate commercially available technology. This includes
                renewable energy from wind, solar, ocean, small hydropower, hydrogen, geothermal and renewable biomass
                (including anaerobic digesters). The maximum grant amount is $500,000, and the maximum loan amount is
                $25 million per applicant.</p>
            <p>Energy efficiency improvement projects eligible for REAP funding include lighting, heating, cooling,
                ventilation, fans, automated controls and insulation upgrades that reduce energy consumption. The
                maximum grant amount is $250,000, and the maximum loan amount is $25 million per applicant.</p>
            <p>Previous loan and grant recipients have used funding to build efficient greenhouses that use solar power
                or re-fit rural grocery stores with more efficient windows, lighting and equipment.</p>
            <p>The REAP application window also has been expanded. USDA said it will now accept and review loan and
                grant applications year-round. Details on how to apply are on page 78029 of the Dec. 29, 2014, Federal
                Register or are available by contacting state Rural Development offices.</p>
            <h2>Additional grants for energy audits</h2>
            <p>USDA is offering a second type of grant to support organizations that help farmers, ranchers and small
                businesses conduct energy audits and operate renewable energy projects.</p>
            <p>Eligible applicants include units of state, tribal or local governments; colleges, universities and other
                institutions of higher learning; rural electric cooperatives and public power entities, and conservation
                and development districts.</p>
            <p>The maximum grant is $100,000. Applications for these particular grants have been available since Dec.
                29, 2014, and are due Feb. 12.</p>
