                <h3>1991</h3>
                <p>Direct Skylights launches its pioneering Tubular Daylighting Device, known as the "SOLA SKYLIGHT with
                    Flexi-tube". Consumers and Installers alike readily embraced the new technology as there were
                    benefits
                    for all including; a much higher efficiency - with more light produced from a significantly smaller
                    product and a huge time saving, as the product had a much easier installation process. Due to the
                    very
                    positive market acceptance of the Sola Skylight and the resultant massive increase in production,
                    Direct
                    Skylights had to relocate to larger premises on five occasions over the next few years.</p>
