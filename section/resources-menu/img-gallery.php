                <p>Sola Skylights International purchases an iconic natural lighting manufacturer also based in Western
                    Australia. The company "Sunlite Skylights" was over 25 years old and had a reputation for
                    manufacturing
                    high quality and heavy duty skylights. Architects continually specified the product and builders
                    preferred them, because they had used them for many years previous and knew they could be relied
                    upon.
                    The addition of Sunlite Skylights to the product range would give Sola Skylights International
                    significant market share in the Commercial Daylighting Market.Sola Skylights International now
                    manufactured & distributed 5 different brand name products and it was decided the company did not
                    want a
                    name that lent itself to one particular product. After analyzing what the company was famous for,
                    the
